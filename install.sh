#!/usr/bin/env bash
# Wire this checkout into VS Code Copilot or Claude Code, or take it out again.
#
#   ./install.sh copilot    symlink instructions, agents, skills and hooks into ~/.copilot/
#   ./install.sh claude     symlink skills into ~/.claude/skills/, write converted agents and rules
#                           into ~/.claude/agents/ and ~/.claude/rules/, add the hooks to
#                           ~/.claude/settings.json (a backup is kept next to it)
#   ./install.sh uninstall  remove everything either target added
#   --dry-run               print what would change, change nothing
#
# Nothing of yours is overwritten: a file that's already there and isn't from this repo is skipped
# and reported, and the script exits 1 so you notice. Copilot target: re-run after adding files.
# Claude target: re-run after every `git pull`, since agents and rules are converted copies.

set -euo pipefail
shopt -s nullglob

REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
COPILOT_DIR=$HOME/.copilot
CLAUDE_DIR=$HOME/.claude
ADAPTER=$REPO/hooks/scripts/claude-adapter.sh
MARK="generated by copilot-dev-os/install.sh"
DRY=0 CONFLICTS=0 CHANGED=0

usage() { sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 2; }
die() { echo "install.sh: $*" >&2; exit 1; }
say() { if ((DRY)); then echo "would $*"; else echo "$*"; fi; }

# Refuse to write into a directory that is itself a symlink: it belongs to some other setup.
ensure_dir() {
  [[ -L "$1" ]] && die "$1 is a symlink to $(readlink "$1"); not writing into it"
  ((DRY)) || mkdir -p "$1"
}

link() {
  local src=$1 dest=$2
  if [[ -L "$dest" && "$(readlink "$dest")" == "$src" ]]; then return; fi
  if [[ -e "$dest" || -L "$dest" ]]; then
    echo "skip $dest: already exists and isn't from this repo" >&2
    CONFLICTS=$((CONFLICTS + 1))
    return
  fi
  say "link $dest -> $src"
  ((DRY)) || ln -s "$src" "$dest"
  CHANGED=$((CHANGED + 1))
}

install_copilot() {
  local f d
  ensure_dir "$COPILOT_DIR/instructions"
  for f in "$REPO"/instructions/*.instructions.md; do link "$f" "$COPILOT_DIR/instructions/${f##*/}"; done
  ensure_dir "$COPILOT_DIR/agents"
  for f in "$REPO"/agents/*.agent.md; do link "$f" "$COPILOT_DIR/agents/${f##*/}"; done
  ensure_dir "$COPILOT_DIR/skills"
  for d in "$REPO"/skills/*/; do d=${d%/}; link "$d" "$COPILOT_DIR/skills/${d##*/}"; done
  ensure_dir "$COPILOT_DIR/hooks"
  ensure_dir "$COPILOT_DIR/hooks/scripts"
  for f in "$REPO"/hooks/*.json; do link "$f" "$COPILOT_DIR/hooks/${f##*/}"; done
  for f in "$REPO"/hooks/scripts/*.sh; do link "$f" "$COPILOT_DIR/hooks/scripts/${f##*/}"; done
  cat <<EOF

VS Code reads ~/.copilot/instructions, ~/.copilot/agents and ~/.copilot/skills by default.
Hooks in the Local agent harness load only from folders you list, so add this to your
VS Code user settings.json (the hooks need jq on PATH):

  "chat.hookFilesLocations": { "~/.copilot/hooks": true }
EOF
}

# Copilot frontmatter -> Claude Code: agents get name/description/model/effort (Copilot tool names
# mean nothing to Claude, so tools are dropped and the agent inherits yours); instructions become
# rules whose applyTo globs turn into `paths` (an applyTo of '**' becomes an always-on rule).
convert_for_claude() {
  python3 - "$REPO" "$CLAUDE_DIR" "$MARK" "$DRY" <<'PY'
import json, re, sys
from pathlib import Path

repo, claude, mark, dry = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3], sys.argv[4] == "1"
conflicts = 0

def split(text):
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.S)
    if not m:
        return {}, text
    meta = {}
    for line in m.group(1).splitlines():
        kv = re.match(r"^([A-Za-z][\w-]*):\s*(.*)$", line)
        if kv:
            v = kv.group(2).strip()
            if len(v) >= 2 and v[0] == v[-1] == "'":
                v = v[1:-1].replace("''", "'")
            elif len(v) >= 2 and v[0] == v[-1] == '"':
                v = v[1:-1].replace('\\"', '"')
            meta[kv.group(1)] = v
    return meta, m.group(2)

def globs(apply_to):
    parts, depth, cur = [], 0, ""
    for ch in apply_to:
        depth += ch == "{"
        depth -= ch == "}"
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return [p.strip() for p in parts if p.strip()]

def write(dest, content, src):
    global conflicts
    if dest.exists() and mark not in dest.read_text(encoding="utf-8", errors="replace"):
        print(f"skip {dest}: already exists and isn't from this repo", file=sys.stderr)
        conflicts += 1
        return
    if dest.exists() and dest.read_text(encoding="utf-8") == content:
        return
    print(("would write " if dry else "write ") + f"{dest} (from {src})")
    if not dry:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content, encoding="utf-8")

def note(src):
    return f"<!-- {mark} from {src}; edit the source and re-run ./install.sh claude -->\n\n"

for f in sorted((repo / "agents").glob("*.agent.md")):
    meta, body = split(f.read_text(encoding="utf-8"))
    slug = f.name.removesuffix(".agent.md")
    head = [f"name: {slug}", "description: " + json.dumps(meta.get("description", slug), ensure_ascii=False)]
    model = meta.get("model", "")
    if "Opus" in model or "Sonnet" in model:
        head.append("model: " + ("opus" if "Opus" in model else "sonnet"))
    effort = meta.get("reasoning-effort", "")
    if effort in {"low", "medium", "high", "xhigh", "max"}:
        head.append(f"effort: {effort}")
    write(claude / "agents" / f"{slug}.md", "---\n" + "\n".join(head) + "\n---\n" + note(f"agents/{f.name}") + body.lstrip(), f"agents/{f.name}")

for f in sorted((repo / "instructions").glob("*.instructions.md")):
    meta, body = split(f.read_text(encoding="utf-8"))
    slug = f.name.removesuffix(".instructions.md")
    paths = globs(meta.get("applyTo", ""))
    head = "" if paths in ([], ["**"]) else "---\npaths:\n" + "".join(f"  - {json.dumps(p)}\n" for p in paths) + "---\n"
    write(claude / "rules" / f"{slug}.md", head + note(f"instructions/{f.name}") + body.lstrip(), f"instructions/{f.name}")

src = repo / "claude" / "copilot-tool-names.md"
write(claude / "rules" / src.name, note(f"claude/{src.name}") + src.read_text(encoding="utf-8"), f"claude/{src.name}")

sys.exit(1 if conflicts else 0)
PY
}

# Add the post-edit lint and the Stop checks to ~/.claude/settings.json through the adapter, which
# turns Claude's tool names and transcript into the VS Code shape the scripts read. Entries from an
# earlier run are replaced, never duplicated.
merge_claude_hooks() {
  local settings=$CLAUDE_DIR/settings.json current merged
  if [[ -f "$settings" ]]; then
    current=$(jq . "$settings" 2>/dev/null) || die "$settings isn't plain JSON (comments?); add the hooks by hand, see README"
  else
    current='{}'
  fi
  merged=$(jq --arg a "$ADAPTER" '
    def ours: any(.hooks[]?; (.command // "") | contains($a));
    def cmd($s): {type: "command", command: ("\"" + $a + "\" " + $s), timeout: 30};
    .hooks //= {}
    | .hooks.PostToolUse = ([.hooks.PostToolUse[]? | select(ours | not)]
        + [{matcher: "Write|Edit|MultiEdit|NotebookEdit", hooks: [cmd("post-edit-lint.sh")]}])
    | .hooks.Stop = ([.hooks.Stop[]? | select(ours | not)] + [{hooks: [cmd("stop.sh")]}])
  ' <<<"$current")
  [[ "$merged" == "$(jq . <<<"$current")" ]] && return
  say "add hooks to $settings"
  ((DRY)) && return
  [[ -f "$settings" && ! -f "$settings.before-copilot-dev-os" ]] && cp "$settings" "$settings.before-copilot-dev-os"
  printf '%s\n' "$merged" >"$settings"
  CHANGED=$((CHANGED + 1))
}

install_claude() {
  local d
  command -v python3 >/dev/null || die "python3 is needed to convert agents and rules"
  command -v jq >/dev/null || die "jq is needed for the hooks"
  ensure_dir "$CLAUDE_DIR/skills"
  for d in "$REPO"/skills/*/; do d=${d%/}; link "$d" "$CLAUDE_DIR/skills/${d##*/}"; done
  ensure_dir "$CLAUDE_DIR/agents"
  ensure_dir "$CLAUDE_DIR/rules"
  convert_for_claude || CONFLICTS=$((CONFLICTS + 1))
  merge_claude_hooks
}

uninstall() {
  local l f settings=$CLAUDE_DIR/settings.json cleaned
  for l in "$COPILOT_DIR"/{instructions,agents,skills,hooks,hooks/scripts}/* "$CLAUDE_DIR"/skills/*; do
    [[ -L "$l" && "$(readlink "$l")" == "$REPO"/* ]] || continue
    say "remove $l"
    ((DRY)) || rm "$l"
  done
  for f in "$CLAUDE_DIR"/agents/*.md "$CLAUDE_DIR"/rules/*.md; do
    grep -qF "$MARK" "$f" || continue
    say "remove $f"
    ((DRY)) || rm "$f"
  done
  [[ -f "$settings" ]] && command -v jq >/dev/null || return 0
  cleaned=$(jq --arg a "$ADAPTER" '
    def ours: any(.hooks[]?; (.command // "") | contains($a));
    if .hooks then .hooks |= (with_entries(.value |= map(select(ours | not))) | with_entries(select(.value != [])))
    else . end
  ' "$settings" 2>/dev/null) || return 0
  [[ "$cleaned" == "$(jq . "$settings")" ]] && return
  say "remove hooks from $settings"
  ((DRY)) || printf '%s\n' "$cleaned" >"$settings"
}

TARGET=""
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY=1 ;;
    copilot|claude|uninstall) [[ -z "$TARGET" ]] || usage; TARGET=$arg ;;
    *) usage ;;
  esac
done
[[ -n "$TARGET" ]] || usage

case "$TARGET" in
  copilot) install_copilot ;;
  claude) install_claude ;;
  uninstall) uninstall ;;
esac

if ((CONFLICTS)); then
  echo "install.sh: done, but $CONFLICTS item(s) were skipped; see the messages above" >&2
  exit 1
fi
[[ "$TARGET" == uninstall ]] || echo "install.sh: $TARGET ready ($CHANGED change(s))"
